// Regenerates app/_lib/countryOutlines.js from @svg-maps/world (public
// domain-ish MIT map data). Run with: npm run generate:outlines
//
// Why pregenerate: the world map ships as one big SVG with every country as
// a fill path in a shared coordinate space. The home continent cards want
// each country on its own — a small line-drawn contour in its own viewBox —
// and computing a path's bounding box needs a path parser, which has no
// business running per-request. So this script does it once and commits the
// result; the module is only ever imported by server components, so none of
// it reaches the client bundle.
import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import pathBounds from "svg-path-bounds";

const require = createRequire(import.meta.url);
const world = require("@svg-maps/world");
const map = world.default || world;

const entries = {};
for (const loc of map.locations) {
  const [minX, minY, maxX, maxY] = pathBounds(loc.path);
  const w = maxX - minX;
  const h = maxY - minY;
  // 4% padding so a stroked outline isn't clipped at the viewBox edge.
  const pad = Math.max(w, h) * 0.04;
  const viewBox = [minX - pad, minY - pad, w + pad * 2, h + pad * 2]
    .map((n) => Math.round(n * 100) / 100)
    .join(" ");
  // Keyed by display name, lowercased — matches prettyGeo() output for the
  // snake_case geography values Sanity stores ("new_zealand" → "new zealand").
  entries[loc.name.toLowerCase()] = { d: loc.path, viewBox };
}

const banner = `// GENERATED by scripts/generate-country-outlines.mjs — do not edit by hand.
// One entry per country: the @svg-maps/world outline path plus a tight
// padded viewBox, keyed by lowercased display name. Server-side only —
// keep this out of client components, it is ~${Math.round(
  JSON.stringify(entries).length / 1024
)}KB of path data.

const OUTLINES = `;

const footer = `;

// Lookup by the country label shown on the site (prettyGeo output). Returns
// null for anything the map doesn't know so callers can just skip the icon.
export function getCountryOutline(country) {
  const key = String(country || "").trim().toLowerCase();
  return OUTLINES[key] || null;
}
`;

await writeFile(
  new URL("../app/_lib/countryOutlines.js", import.meta.url),
  banner + JSON.stringify(entries) + footer
);
console.log(`Wrote ${Object.keys(entries).length} country outlines.`);
